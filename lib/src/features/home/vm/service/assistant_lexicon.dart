/// Словарь помощника подбора заказа.
///
/// Сервер присылает только названия, описания и категории — без признаков
/// «острое», «без мяса», «на компанию». Всё это помощник узнаёт по словам на
/// трёх языках меню (ru / kk / en) и по иероглифам в меню китайских
/// заведений. Нашли в реальном меню слово, которое помощник не понял, —
/// дописываем сюда.
library;

/// Набор слов: короткие и двусмысленные — только целым токеном («сок», но
/// не «сокровище»), остальные — по корню, то есть по началу токена.
class WordSet {
  const WordSet({
    this.exact = const {},
    this.stems = const [],
    this.except = const [],
  });

  final Set<String> exact;
  final List<String> stems;

  /// Корни-исключения: «острова» начинается с «остр», но это не острое.
  final List<String> except;

  /// Корни по первой букве: токен сверяется только с корнями на ту же
  /// букву, а не со всеми сотнями подряд. Класс константный, поэтому
  /// индекс живёт снаружи и строится при первом обращении.
  static final Expando<Map<int, List<String>>> _indexes = Expando();

  Map<int, List<String>> get _index => _indexes[this] ??= {
        for (final first in {for (final stem in stems) stem.codeUnitAt(0)})
          first: [
            for (final stem in stems)
              if (stem.codeUnitAt(0) == first) stem,
          ],
      };

  bool matches(String token) {
    if (token.isEmpty) return false;
    if (exact.contains(token)) return true;
    final candidates = _index[token.codeUnitAt(0)];
    if (candidates == null) return false;
    if (except.isNotEmpty && except.any(token.startsWith)) return false;
    for (final stem in candidates) {
      if (token.startsWith(stem)) return true;
    }
    return false;
  }

  bool any(Iterable<String> tokens) => tokens.any(matches);
}

